"""Writes results_v2/V3_RESULTS.md from tables/v3_models.csv (all numbers come from the table)."""
from __future__ import annotations

import os

import pandas as pd

from common_v2 import RES, TAB

HEAD = "Hybrid(TabPFN+TempoSAR+Trees)"
KEY = [  # (label, model, provenance)
    ("v2 headline (unchanged)", HEAD, "v2"),
    ("TabPFN, v2 run", "TabPFN", "v2"),
    ("TabPFN bag 0 re-run (installed TabPFN version)", "TabPFN-bag0(rerun)", "pre-registered"),
    ("TabPFN bag of 5 contexts", "TabPFN-bag5", "pre-registered"),
    ("Hybrid with TabPFN-bag5", "Hybrid(TabPFN-bag5+TempoSAR+Trees)", "pre-registered"),
    ("Hybrid + station-mean (w=0.5) — declared v3 candidate", f"{HEAD} +StationMean(w=0.5)", "pre-registered"),
    ("Hybrid + station-mean (w nested)", f"{HEAD} +StationMean(w nested)", "pre-registered"),
    ("Trees + POLARIS", "Trees+POLARIS", "exploratory"),
    ("TabPFN + POLARIS", "TabPFN+POLARIS", "exploratory"),
    ("Hybrid with Trees+POLARIS", "Hybrid(TabPFN+TempoSAR+Trees+POLARIS)", "exploratory"),
    ("Hybrid with TabPFN-bag5 and Trees+POLARIS", "Hybrid(TabPFN-bag5+TempoSAR+Trees+POLARIS)", "exploratory"),
    ("Hybrid, all members with POLARIS where run", "Hybrid(TabPFN+POLARIS+TempoSAR+Trees+POLARIS)", "exploratory"),
    ("Hybrid + station-mean with POLARIS (w=0.5)", f"{HEAD} +StationMean+POLARIS(w=0.5)", "exploratory"),
    ("Hybrid with Trees+POLARIS + station-mean with POLARIS (w=0.5)",
     "Hybrid(TabPFN+TempoSAR+Trees+POLARIS) +StationMean+POLARIS(w=0.5)", "exploratory"),
]


def fmt(r):
    return (f"| {r.R2:.3f} [{r.R2_lo:.3f}, {r.R2_hi:.3f}] | {r.RMSE:.2f} | {r.ubRMSE:.2f} | {r.bias:+.2f} | "
            f"{r.site_median_r:.3f} | {r.dR2_vs_head:+.3f} [{r.dR2_lo:+.3f}, {r.dR2_hi:+.3f}] |")


def main():
    t = pd.read_csv(os.path.join(TAB, "v3_models.csv"))
    L = ["# v3 results — improvements on the 2019–2023 satellite-only benchmark", "",
         "Generated by `src_v2/summary_v3.py` from `tables/v3_models.csv`; do not edit by hand.",
         "The pre-registration is in `progress.md` (2026-11-22), written before any v3 result existed.",
         "CIs come from a station-cluster bootstrap (1000 resamples). ΔR² is paired against the v2 headline. Nothing is fitted on test stations.", "",
         "**Provenance.** *pre-registered* rows were declared before results. *exploratory* rows (POLARIS) were "
         "added after the pre-registered station-mean correction failed. Label them exploratory in the paper.", ""]
    for proto in ["leave-stations-out", "leave-one-region-out", "temporal(2022-23)"]:
        s = t[t.protocol == proto].set_index("model")
        L += [f"## {proto}", "",
              "| Row | provenance | R² [95% CI] | RMSE | ubRMSE | bias | median station r | ΔR² vs v2 headline [95% CI] |",
              "|---|---|---|---|---|---|---|---|"]
        for label, m, prov in KEY:
            if m in s.index:
                L.append(f"| {label} | {prov} " + fmt(s.loc[m]))
        L.append("")
    REF4 = "Hybrid(TabPFN-bag5+TempoSAR+Trees+POLARIS)"
    KEY4 = [("v4 reference", REF4), ("Trees+POLARIS(exact)", "Trees+POLARIS(exact)"),
            ("Trees+POLARIS(Se)", "Trees+POLARIS(Se)"), ("Trees+POLARIS(exact, Se)", "Trees+POLARIS(exact, Se)"),
            ("Hybrid, exact-coordinate POLARIS (v4-1)", "Hybrid(TabPFN-bag5+TempoSAR+Trees+POLARIS(exact))"),
            ("Hybrid, Se target (v4-2)", "Hybrid(TabPFN-bag5+TempoSAR+Trees+POLARIS(Se))"),
            ("Hybrid, exact + Se", "Hybrid(TabPFN-bag5+TempoSAR+Trees+POLARIS(exact, Se))"),
            ("TempoSAR re-run on Kaggle (control)", "TempoSAR(rerun)"), ("TempoSAR+POLARIS (v4-3)", "TempoSAR+POLARIS"),
            ("Hybrid with TempoSAR control", "Hybrid(TabPFN-bag5+TempoSAR(rerun)+Trees+POLARIS)"),
            ("Hybrid with TempoSAR+POLARIS", "Hybrid(TabPFN-bag5+TempoSAR+POLARIS+Trees+POLARIS)"),
            ("**v4 candidate** (declared before results)", "Hybrid(TabPFN-bag5+TempoSAR+POLARIS+Trees+POLARIS(exact, Se))")]
    L += ["# v4 (pre-registered 2026-11-22; reference = v3 exploratory best row)", ""]
    for proto in ["leave-stations-out", "leave-one-region-out"]:
        s = t[t.protocol == proto].set_index("model")
        if "dR2_vs_v4ref" not in s:
            continue
        L += [f"## v4, {proto}", "",
              "| Row | R² [95% CI] | RMSE | bias | median station r | ΔR² vs v2 headline | ΔR² vs v4 reference [95% CI] |",
              "|---|---|---|---|---|---|---|"]
        for label, m in KEY4:
            if m in s.index:
                r = s.loc[m]
                L.append(f"| {label} | {r.R2:.3f} [{r.R2_lo:.3f}, {r.R2_hi:.3f}] | {r.RMSE:.2f} | {r.bias:+.2f} | "
                         f"{r.site_median_r:.3f} | {r.dR2_vs_head:+.3f} | {r.dR2_vs_v4ref:+.3f} "
                         f"[{r.dR2_lo_v4ref:+.3f}, {r.dR2_hi_v4ref:+.3f}] |")
            else:
                L.append(f"| {label} | not run / incomplete | | | | | |")
        L.append("")
    dfn = os.path.join(TAB, "v4_daily.csv")
    if os.path.exists(dfn):
        d = pd.read_csv(dfn)
        L += ["# v4 daily: every labelled day (`exp_v4_daily.py`, from `tables/v4_daily.csv`)", "",
              "Anchor models predict only on Sentinel-1 dates; their out-of-fold estimates are held or linearly "
              "interpolated onto every day at the same held-out station (no fitting). Linear interpolation uses the "
              "next Sentinel-1 date, so it is a reconstruction, not a real-time product (hold-last is). All rows are "
              "scored on the same days. ΔR² is paired against the v2 hybrid with linear interpolation.", ""]
        for proto in ["leave-stations-out", "leave-one-region-out"]:
            s = d[d.protocol == proto]
            if s.empty:
                continue
            L += [f"## v4 daily, {proto}", "",
                  "| Model | days | n | R² [95% CI] | RMSE | bias | median station r | ΔR² vs v2 interp [95% CI] |",
                  "|---|---|---|---|---|---|---|---|"]
            for r in s.itertuples():
                ci = f" [{r.R2_lo:.3f}, {r.R2_hi:.3f}]" if pd.notna(r.R2_lo) else ""
                dci = f" [{r.dR2_lo:+.3f}, {r.dR2_hi:+.3f}]" if pd.notna(r.dR2_lo) else " (reference)"
                L.append(f"| {r.model} | {r.days} | {r.n} | {r.R2:.3f}{ci} | {r.RMSE:.2f} | {r.bias:+.2f} | "
                         f"{r.site_median_r:.3f} | {r.dR2_vs_v2interp:+.3f}{dci} |")
            L.append("")
    L += ["## What the numbers say", "",
          "1. About 58 % of the hybrid's MSE at unseen stations is a constant per-station offset (bias). It is not day-to-day error.",
          "2. A second-stage station-mean model built from the existing v2 satellite/static features does not reduce that "
          "offset. Its station-mean errors are 0.94 correlated with the hybrid's.",
          "3. Adding POLARIS 30 m SSURGO-based soil properties (static map product, no in-situ input) reduces it. "
          "It is the only change that clears the bootstrap noise floor (about ±0.01 R²) at unseen stations and unseen regions.",
          "4. Median per-station r is essentially unchanged by every v3 change. The gains are in bias and level, not in temporal dynamics.",
          "5. v4: re-extracting POLARIS at the exact NRCS coordinates and fitting the trees on relative wetness "
          "(Se) are both null (|ΔR²| <= 0.001 vs the v4 reference). The models use the ~1 km window means, which barely "
          "change with the coordinates. The trees already receive porosity as an input.",
          "6. stations.csv coordinates are off by > 1 km at 21 of the 184 evaluated stations. Two are badly off: Starkville "
          "17.7 km, Lovelock 27.5 km. All satellite features there were sampled at the wrong place; re-extracting them "
          "needs Earth Engine.",
          "7. v4-3: TempoSAR with POLARIS static inputs beats its own re-run control as a single model "
          "(see the TempoSAR rows above). Inside the hybrid it adds only a few thousandths of R² over the v4 reference, "
          "and the CI includes 0. The declared v4 candidate stays well above the v2 headline at unseen stations and regions.",
          "8. Daily: the v4 final hybrid, linearly interpolated between Sentinel-1 dates, keeps most of its gain "
          "on non-Sentinel-1 days (see the v4 daily tables). Averaging it with the v2 LGBM-daily model is "
          "better still, but that row is exploratory.",
          "9. Not done: spatially blocked folds, rolling-origin split, nested stacking, satellite re-extraction at "
          "the exact coordinates.", ""]
    with open(os.path.join(RES, "V3_RESULTS.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
